"""Operator-only PostgreSQL accounting and diagnostic event history."""

from __future__ import annotations

from contextlib import contextmanager

from mnogobase.config import LLMRate
from mnogobase.database import DatabaseTarget, connect, initialize, transaction_lock
from mnogobase.llm.telemetry import CallEvent
from mnogobase.log import get_logger

_SCHEMA = """
CREATE TABLE IF NOT EXISTS llm_usage (
    id TEXT PRIMARY KEY, team_id TEXT NOT NULL REFERENCES teams(id), model TEXT NOT NULL,
    operation TEXT NOT NULL, created_at DOUBLE PRECISION NOT NULL, job_id BIGINT,
    external BOOLEAN NOT NULL, status TEXT NOT NULL,
    tokens_in BIGINT, tokens_out BIGINT, currency TEXT,
    input_rate NUMERIC, output_rate NUMERIC, estimated_cost NUMERIC
);
CREATE INDEX IF NOT EXISTS llm_usage_team_time ON llm_usage(team_id, created_at);
CREATE TABLE IF NOT EXISTS worker_heartbeat (
    name TEXT PRIMARY KEY, expected_since DOUBLE PRECISION NOT NULL, last_seen DOUBLE PRECISION
);
CREATE TABLE IF NOT EXISTS service_alerts (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    team_id TEXT NOT NULL, kind TEXT NOT NULL, subject TEXT NOT NULL,
    first_seen DOUBLE PRECISION NOT NULL, last_seen DOUBLE PRECISION NOT NULL,
    resolved_at DOUBLE PRECISION
);
CREATE UNIQUE INDEX IF NOT EXISTS service_alerts_active ON service_alerts(team_id,kind,subject)
    WHERE resolved_at IS NULL;
"""


class ObservabilityStore:
    def __init__(self, target: DatabaseTarget):
        self.target = target
        with self._connection() as db:
            initialize(db, _SCHEMA, "observability")

    @contextmanager
    def _connection(self):
        db = connect(self.target)
        try:
            yield db
        finally:
            db.close()

    def record_usage(self, event: CallEvent, rate: LLMRate | None = None) -> None:
        """A local attempt ID is stable across start/result and persistence retries."""
        if not event.external:
            rate = None
        with self._connection() as db, db:
            db.execute(
                "INSERT INTO llm_usage(id,team_id,model,operation,created_at,job_id,external,status,"
                "currency,input_rate,output_rate) VALUES(?,?,?,?,?,?,?,'started',?,?,?) "
                "ON CONFLICT(id) DO NOTHING",
                (
                    event.id,
                    event.team_id,
                    event.model,
                    event.operation,
                    event.created_at,
                    event.job_id,
                    event.external,
                    rate.currency if rate else None,
                    rate.input_per_million if rate else None,
                    rate.output_per_million if rate else None,
                ),
            )
            if event.status != "started":
                db.execute(
                    "UPDATE llm_usage SET status=?,tokens_in=?,tokens_out=?,"
                    "estimated_cost=(? * input_rate + ? * output_rate)/1000000 "
                    "WHERE id=? AND team_id=? AND status='started'",
                    (
                        event.status,
                        event.tokens_in,
                        event.tokens_out,
                        event.tokens_in,
                        event.tokens_out,
                        event.id,
                        event.team_id,
                    ),
                )

    def usage(
        self, *, team_id: str | None = None, since: float | None = None, until: float | None = None
    ) -> list[dict]:
        clauses, args = [], []
        for clause, value in (
            ("team_id=?", team_id),
            ("created_at>=?", since),
            ("created_at<?", until),
        ):
            if value is not None:
                clauses.append(clause)
                args.append(value)
        where = " WHERE " + " AND ".join(clauses) if clauses else ""
        with self._connection() as db:
            rows = db.execute(
                "SELECT team_id,model,operation,currency,external,COUNT(*) AS calls,"
                "SUM(tokens_in) AS tokens_in,SUM(tokens_out) AS tokens_out,"
                "COUNT(*) FILTER (WHERE tokens_in IS NULL OR tokens_out IS NULL) AS unknown_usage,"
                "COUNT(*) FILTER (WHERE external AND estimated_cost IS NULL) AS unpriced_calls,"
                "COUNT(*) FILTER (WHERE status='error') AS errors,"
                "COUNT(*) FILTER (WHERE status='started') AS incomplete_calls,"
                "SUM(estimated_cost) AS estimated_cost FROM llm_usage"
                + where
                + " GROUP BY team_id,model,operation,currency,external ORDER BY team_id,model,operation,currency",
                tuple(args),
            ).fetchall()
        result = [dict(r) for r in rows]
        for row in result:
            for field in ("tokens_in", "tokens_out"):
                if row[field] is not None:
                    row[field] = int(row[field])
            if row["estimated_cost"] is not None:
                row["estimated_cost"] = str(row["estimated_cost"])
        return result

    def heartbeat(self, now: float) -> None:
        with self._connection() as db:
            db.execute(
                "INSERT INTO worker_heartbeat VALUES('service',?,?) ON CONFLICT(name) "
                "DO UPDATE SET last_seen=excluded.last_seen",
                (now, now),
            )

    def worker_seen(self, now: float) -> float:
        with self._connection() as db:
            db.execute(
                "INSERT INTO worker_heartbeat(name,expected_since) VALUES('service',?) "
                "ON CONFLICT(name) DO NOTHING",
                (now,),
            )
            return db.execute(
                "SELECT COALESCE(last_seen,expected_since) FROM worker_heartbeat "
                "WHERE name='service'"
            ).fetchone()[0]

    def reconcile(self, conditions: set[tuple[str, str, str]], *, now: float) -> None:
        """Serialize concurrent scans; each recurrence gets a new history row."""
        transitions = []
        with self._connection() as db, db:
            transaction_lock(db, "service-alerts")
            active = {
                (r["team_id"], r["kind"], r["subject"]): r["id"]
                for r in db.execute("SELECT * FROM service_alerts WHERE resolved_at IS NULL")
            }
            for key in sorted(conditions):
                if key in active:
                    db.execute(
                        "UPDATE service_alerts SET last_seen=? WHERE id=?", (now, active[key])
                    )
                else:
                    db.execute(
                        "INSERT INTO service_alerts(team_id,kind,subject,first_seen,last_seen) "
                        "VALUES(?,?,?,?,?)",
                        (*key, now, now),
                    )
                    transitions.append(("service_alert_opened", key))
            for key in active.keys() - conditions:
                db.execute("UPDATE service_alerts SET resolved_at=? WHERE id=?", (now, active[key]))
                transitions.append(("service_alert_resolved", key))
        log = get_logger(__name__)
        for event, (team_id, kind, subject) in transitions:
            log.warning(event, team_id=team_id or None, kind=kind, subject=subject)

    def alerts(
        self,
        *,
        team_id: str | None = None,
        history: bool = False,
        limit: int = 100,
        offset: int = 0,
    ) -> list[dict]:
        if not 1 <= limit <= 1000 or offset < 0:
            raise ValueError("Invalid pagination")
        clauses, args = ([] if history else ["resolved_at IS NULL"]), []
        if team_id is not None:
            clauses.append("team_id=?")
            args.append(team_id)
        where = " WHERE " + " AND ".join(clauses) if clauses else ""
        with self._connection() as db:
            return [
                dict(r)
                for r in db.execute(
                    "SELECT * FROM service_alerts" + where + " ORDER BY id DESC LIMIT ? OFFSET ?",
                    (*args, limit, offset),
                )
            ]
