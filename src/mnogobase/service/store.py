"""Пользователи, отзываемые сессии и личные диалоги (в схеме проекта)."""

from __future__ import annotations

import hashlib
import json
import secrets
import threading
import time
import uuid
from collections.abc import Iterator
from contextlib import contextmanager

from argon2 import PasswordHasher
from argon2.exceptions import VerificationError
from sqlalchemy.exc import IntegrityError, OperationalError

from mnogobase.database import (
    DatabaseTarget,
    PgConnection,
    Row,
    connect,
    initialize,
    utc_timestamp,
)
from mnogobase.log import get_logger
from mnogobase.service.errors import ServiceError, check_pagination

MIN_PASSWORD = 12
# argon2 берёт 64 MiB на хеш: без предела параллельные логины исчерпали бы память.
_ARGON2_SLOTS = threading.BoundedSemaphore(2)
_ARGON2_WAIT_S = 5.0

_SCHEMA = """
CREATE TABLE IF NOT EXISTS users (
    id TEXT PRIMARY KEY, username TEXT NOT NULL UNIQUE, password_hash TEXT NOT NULL,
    active INTEGER NOT NULL DEFAULT 1 CHECK(active IN (0, 1))
);
CREATE TABLE IF NOT EXISTS sessions (
    token_hash TEXT PRIMARY KEY, user_id TEXT NOT NULL REFERENCES users(id),
    expires_at DOUBLE PRECISION NOT NULL
);
CREATE INDEX IF NOT EXISTS sessions_user ON sessions(user_id);
CREATE TABLE IF NOT EXISTS conversations (
    seq BIGINT GENERATED BY DEFAULT AS IDENTITY UNIQUE,
    id TEXT PRIMARY KEY, user_id TEXT NOT NULL REFERENCES users(id),
    title TEXT NOT NULL, created_at TEXT NOT NULL,
    UNIQUE(id, user_id)
);
CREATE INDEX IF NOT EXISTS conversations_owner ON conversations(user_id, created_at);
CREATE TABLE IF NOT EXISTS messages (
    seq BIGINT GENERATED BY DEFAULT AS IDENTITY UNIQUE,
    id TEXT PRIMARY KEY, conversation_id TEXT NOT NULL, user_id TEXT NOT NULL,
    role TEXT NOT NULL, content TEXT NOT NULL,
    mode TEXT NOT NULL, sources TEXT NOT NULL, status TEXT NOT NULL, query TEXT,
    created_at TEXT NOT NULL,
    FOREIGN KEY(conversation_id, user_id) REFERENCES conversations(id, user_id)
);
CREATE INDEX IF NOT EXISTS messages_owner ON messages(user_id, conversation_id, created_at);
"""
_MIGRATIONS = (
    # v2: роли пользователей остались от командного режима; владелец у базы один
    "ALTER TABLE users DROP COLUMN IF EXISTS role",
)


def _record(row) -> dict:
    record = dict(row)
    record.pop("seq", None)
    return record


def _token_hash(token: str) -> str:
    return hashlib.sha256(token.encode()).hexdigest()


def _check_password(password: str) -> None:
    if len(password) < MIN_PASSWORD:
        raise ServiceError(400, f"Password must have at least {MIN_PASSWORD} characters")


class ServiceStore:
    def __init__(self, target: DatabaseTarget):
        self.target = target
        self._passwords = PasswordHasher()
        conn = connect(target)
        try:
            initialize(conn, _SCHEMA, "service", _MIGRATIONS)
        finally:
            conn.close()

    @contextmanager
    def _connection(self, *, write: bool = False) -> Iterator[PgConnection]:
        conn = connect(self.target)
        try:
            if write:
                conn.execute("BEGIN")
            with conn:
                yield conn
        except OperationalError as exc:
            if getattr(getattr(exc, "orig", None), "sqlstate", None) in {
                "55P03",
                "40P01",
                "40001",
            }:
                raise ServiceError(409, "Service database is busy") from None
            raise
        finally:
            conn.close()

    @contextmanager
    def _argon2(self) -> Iterator[None]:
        if not _ARGON2_SLOTS.acquire(timeout=_ARGON2_WAIT_S):
            raise ServiceError(429, "Too many login attempts; retry later")
        try:
            yield
        finally:
            _ARGON2_SLOTS.release()

    def _hash(self, password: str) -> str:
        with self._argon2():
            return self._passwords.hash(password)

    # ---- пользователи (только из CLI) ----
    def create_user(self, username: str, password: str) -> dict:
        username = username.strip()
        if not username:
            raise ServiceError(400, "Username is required")
        _check_password(password)
        user = {"id": uuid.uuid4().hex, "username": username}
        password_hash = self._hash(password)
        try:
            with self._connection(write=True) as conn:
                conn.execute(
                    "INSERT INTO users(id, username, password_hash) VALUES(?, ?, ?)",
                    (user["id"], username, password_hash),
                )
        except IntegrityError:
            raise ServiceError(409, "Username already exists") from None
        return user

    def _user_id(self, conn: PgConnection, username: str) -> str:
        row = conn.execute(
            "SELECT id FROM users WHERE username=? FOR UPDATE", (username.strip(),)
        ).fetchone()
        if row is None:
            raise ServiceError(404, "User not found")
        return row["id"]

    def set_password(self, username: str, password: str) -> None:
        """Новый пароль; все сессии пользователя отзываются."""
        _check_password(password)
        password_hash = self._hash(password)
        with self._connection(write=True) as conn:
            user_id = self._user_id(conn, username)
            conn.execute("UPDATE users SET password_hash=? WHERE id=?", (password_hash, user_id))
            conn.execute("DELETE FROM sessions WHERE user_id=?", (user_id,))

    def set_active(self, username: str, active: bool) -> None:
        with self._connection(write=True) as conn:
            user_id = self._user_id(conn, username)
            conn.execute("UPDATE users SET active=? WHERE id=?", (int(active), user_id))
            if not active:
                conn.execute("DELETE FROM sessions WHERE user_id=?", (user_id,))

    def users(self) -> list[dict]:
        with self._connection() as conn:
            rows = conn.execute(
                "SELECT id, username, active FROM users ORDER BY username"
            ).fetchall()
        return [dict(r) for r in rows]

    # ---- сессии ----
    def login(self, username: str, password: str, ttl_hours: int = 24) -> str:
        if not isinstance(ttl_hours, (int, float)) or not 0 < ttl_hours <= 24 * 365:
            raise ServiceError(400, "Invalid session lifetime")
        with self._connection() as conn:
            user = conn.execute(
                "SELECT * FROM users WHERE username=? AND active=1", (username.strip(),)
            ).fetchone()
        try:
            with self._argon2():
                if user is None:
                    # Match the verification cost for unknown users without creating a session.
                    self._passwords.hash(password)
                    raise VerificationError
                self._passwords.verify(user["password_hash"], password)
        except VerificationError:
            # Имя хешируется: лог пригоден для fail2ban и не раскрывает логины.
            get_logger(__name__).warning(
                "login_failed",
                user=hashlib.sha256(username.strip().encode()).hexdigest()[:12],
            )
            raise ServiceError(401, "Invalid username or password") from None
        token = secrets.token_urlsafe(32)
        with self._connection(write=True) as conn:
            # A disable between verification and this write must also reject the login.
            if not conn.execute(
                "SELECT id FROM users WHERE id=? AND active=1 FOR UPDATE",
                (user["id"],),
            ).fetchone():
                raise ServiceError(401, "Invalid username or password")
            conn.execute("DELETE FROM sessions WHERE expires_at<=?", (time.time(),))
            conn.execute(
                "INSERT INTO sessions(token_hash, user_id, expires_at) VALUES(?, ?, ?)",
                (_token_hash(token), user["id"], time.time() + ttl_hours * 3600),
            )
        return token

    def authenticate(self, token: str) -> dict:
        with self._connection() as conn:
            user = conn.execute(
                "SELECT u.id, u.username FROM users u JOIN sessions s ON s.user_id=u.id "
                "WHERE s.token_hash=? AND s.expires_at>? AND u.active=1",
                (_token_hash(token), time.time()),
            ).fetchone()
            if user is None:
                raise ServiceError(401, "Invalid or expired session")
            return dict(user)

    def logout(self, token: str) -> None:
        with self._connection(write=True) as conn:
            conn.execute("DELETE FROM sessions WHERE token_hash=?", (_token_hash(token),))

    # ---- диалоги ----
    def _conversation(self, conn: PgConnection, user_id: str, conversation_id: str) -> Row:
        chat = conn.execute(
            "SELECT * FROM conversations WHERE id=? AND user_id=?", (conversation_id, user_id)
        ).fetchone()
        if chat is None:
            raise ServiceError(404, "Conversation not found")
        return chat

    def create_conversation(self, user_id: str, title: str = "") -> dict:
        chat = {
            "id": uuid.uuid4().hex,
            "user_id": user_id,
            "title": title,
            "created_at": utc_timestamp(),
        }
        with self._connection(write=True) as conn:
            conn.execute(
                "INSERT INTO conversations(id, user_id, title, created_at) "
                "VALUES(:id, :user_id, :title, :created_at)",
                chat,
            )
        return chat

    def conversations(self, user_id: str, limit: int = 50, offset: int = 0) -> list[dict]:
        check_pagination(limit, offset)
        with self._connection() as conn:
            return [
                _record(row)
                for row in conn.execute(
                    "SELECT * FROM conversations WHERE user_id=? "
                    "ORDER BY created_at DESC, seq DESC LIMIT ? OFFSET ?",
                    (user_id, limit, offset),
                )
            ]

    def conversation(self, user_id: str, conversation_id: str) -> dict:
        with self._connection() as conn:
            return _record(self._conversation(conn, user_id, conversation_id))

    @staticmethod
    def _message(row: Row) -> dict:
        message = _record(row)
        message["sources"] = json.loads(message["sources"])
        return message

    def messages(
        self, user_id: str, conversation_id: str, limit: int = 100, offset: int = 0
    ) -> list[dict]:
        check_pagination(limit, offset)
        with self._connection() as conn:
            self._conversation(conn, user_id, conversation_id)
            return [
                self._message(row)
                for row in conn.execute(
                    "SELECT * FROM messages WHERE conversation_id=? AND user_id=? "
                    "ORDER BY created_at, seq LIMIT ? OFFSET ?",
                    (conversation_id, user_id, limit, offset),
                )
            ]

    def recent_messages(self, user_id: str, conversation_id: str, limit: int = 12) -> list[dict]:
        """Последние сообщения в хронологическом порядке, без загрузки всего чата."""
        check_pagination(limit, 0)
        with self._connection() as conn:
            self._conversation(conn, user_id, conversation_id)
            rows = conn.execute(
                "SELECT * FROM messages WHERE conversation_id=? AND user_id=? "
                "ORDER BY created_at DESC, seq DESC LIMIT ?",
                (conversation_id, user_id, limit),
            ).fetchall()
            return [self._message(row) for row in reversed(rows)]

    def append_message(
        self,
        user_id: str,
        conversation_id: str,
        role: str,
        content: str,
        *,
        mode: str = "rag",
        sources: list | None = None,
        status: str = "done",
        query: str | None = None,
    ) -> dict:
        if role not in {"user", "assistant", "system"}:
            raise ServiceError(400, "Invalid message role")
        if sources is not None and not isinstance(sources, list):
            raise ServiceError(400, "Invalid message sources")
        try:
            sources_json = json.dumps(sources if sources is not None else [], ensure_ascii=False)
        except (TypeError, ValueError):
            raise ServiceError(400, "Invalid message sources") from None
        message = {
            "id": uuid.uuid4().hex,
            "conversation_id": conversation_id,
            "user_id": user_id,
            "role": role,
            "content": content,
            "mode": mode,
            "sources": sources_json,
            "status": status,
            "query": query,
            "created_at": utc_timestamp(),
        }
        with self._connection(write=True) as conn:
            self._conversation(conn, user_id, conversation_id)
            conn.execute(
                "INSERT INTO messages(id, conversation_id, user_id, role, content, mode, "
                "sources, status, query, created_at) VALUES(:id, :conversation_id, :user_id, "
                ":role, :content, :mode, :sources, :status, :query, :created_at)",
                message,
            )
        message["sources"] = json.loads(sources_json)
        return message
