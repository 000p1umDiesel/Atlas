import { createDistinctPalette, type ThemedColor } from "./communityPalette";

/*
 * Цвета типов сущностей. Типов в config.yaml 15, а прежних токенов --t1..--t8 — восемь
 * (по кругу два типа получали один цвет). Теперь цвет типа даёт тот же различимый
 * генератор, что и сообществам: детерминированно по порядку типов в списке.
 *
 * Прежние восемь токенов не сохранены: подобраны под соседние пары, попарно они
 * сходятся до ΔE 6.3 (горчица и олива), а лучшее подмножество из шести даёт на 15
 * типах 10.2 / 10.1 против 12.1 / 10.5 у чистого генератора. Оставлен только первый —
 * «глина» --t1. Сетка хромы — от 0.10 (порог dataviz: ниже оттенок читается как серый).
 *
 * Минимальное попарное ΔE (OKLab ×100, светлая / тёмная; проверяется тестом):
 *   N = 8 → 17.9 / 16.9, 15 → 12.1 / 10.5, 20 → 7.9 / 7.5.
 * Цвет — не единственный признак: тип всегда подписан рядом (чип, легенда, подсказка).
 */

/** Нижняя граница попарного ΔE для 15 типов в обеих темах. */
export const TYPE_PALETTE_FLOOR = 10;

const typePalette = createDistinctPalette({
  chromas: [0.1, 0.13, 0.17],
  // Запас над порогом 0.10: в тёмной теме хрома ×0.92, а ужатые охватом sRGB кандидаты
  // (тёмная бирюза) иначе оказались бы ниже порога.
  minChroma: 0.105,
  seed: { light: "#e08a6c", dark: "#d77755" },
});

/** Цвет i-го типа в списке настроенных типов. */
export function typeColorAt(index: number): ThemedColor {
  return typePalette(index);
}

/** Цвета типов по порядку списка; тот же список — те же цвета. */
export function typeColors(types: readonly string[]): Map<string, ThemedColor> {
  return new Map(types.map((type, i) => [type, typeColorAt(i)]));
}
