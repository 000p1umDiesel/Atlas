import { createDistinctPalette, type ThemedColor } from "./communityPalette";

/*
 * Цвета типов сущностей. Типов в config.yaml 18, а прежних токенов --t1..--t8 было восемь
 * (по кругу несколько типов получали один цвет). Теперь цвет типа даёт тот же различимый
 * генератор, что и сообществам: детерминированно по порядку типов в списке. Последний тип
 * `Other` («Другое») — не категория, а «всё остальное»: он нейтральный, как тип вне списка,
 * и слот палитры не занимает. Цветных типов — 17.
 *
 * Прежние восемь токенов не сохранены: подобраны под соседние пары, попарно они
 * сходятся до ΔE 6.3 (горчица и олива); любое их подмножество в затравке даёт худший
 * минимум, чем чистый генератор. Оставлен только первый — «глина» --t1. Сетка хромы —
 * от 0.10 (порог dataviz: ниже оттенок читается как серый).
 *
 * Измерено (OKLab ×100, светлая / тёмная; границы проверяются тестом):
 *   минимальное попарное ΔE: N = 8 → 17.9 / 16.9, 15 → 12.1 / 10.5, 17 → 9.2 / 8.9, 20 → 8.2 / 7.5;
 *   соседние пары при протанопии/дейтеранопии, N = 17: 4.6 / 2.3 (ниже порога dataviz 6–8).
 * 17 категорий не проходят пороги dataviz для всех пар — это предел для такого числа цветов.
 * Поэтому цвет никогда не единственный признак: тип всегда подписан рядом (чип, легенда,
 * подсказка, карточка, полосы, справочник).
 */

/** Нижняя граница попарного ΔE для 17 цветных типов в обеих темах (измерено 9.2 / 8.9). */
export const TYPE_PALETTE_FLOOR = 8.5;
/** Нижняя граница ΔE соседних цветов при протанопии/дейтеранопии, 17 типов (измерено 4.6 / 2.3). */
export const TYPE_ADJACENT_CVD_FLOOR = { light: 4.5, dark: 2.2 } as const;

/** Тип «всё остальное» из config.yaml: нейтральный цвет, как у типа вне списка. */
export const NEUTRAL_TYPES: ReadonlySet<string> = new Set(["Other"]);

const typePalette = createDistinctPalette({
  chromas: [0.1, 0.13, 0.17],
  // Запас над порогом 0.10: в тёмной теме хрома ×0.92, а ужатые охватом sRGB кандидаты
  // (тёмная бирюза) иначе оказались бы ниже порога.
  minChroma: 0.105,
  seed: { light: "#e08a6c", dark: "#d77755" },
});

/** Цвет i-го типа в списке настроенных типов. */
export function typeColorAt(index: number): ThemedColor {
  return typePalette(index);
}

/**
 * Слот палитры типа: позиция среди цветных типов списка (нейтральные слот не занимают);
 * -1 — тип вне списка или нейтральный.
 */
export function typeColorIndex(type: string, order: readonly string[]): number {
  if (NEUTRAL_TYPES.has(type)) return -1;
  return order.filter((t) => !NEUTRAL_TYPES.has(t)).indexOf(type);
}

/** Цвета цветных типов по порядку списка; тот же список — те же цвета. Нейтральных в карте нет. */
export function typeColors(types: readonly string[]): Map<string, ThemedColor> {
  const colored = types.filter((t) => !NEUTRAL_TYPES.has(t));
  return new Map(colored.map((type, i) => [type, typeColorAt(i)]));
}
